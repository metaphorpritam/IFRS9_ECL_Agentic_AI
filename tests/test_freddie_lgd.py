# ---------------------------------------------------------------------------
# 8. population_lgd_summary: "loss not yet finalized" liquidations must be
#    EXCLUDED from mean_realized_lgd, never zero-filled (a prior version of
#    this function silently treated a missing actual_loss_calculation as a
#    $0 loss, biasing mean_realized_lgd down -- see fit_lgd.py's docstring
#    on population_lgd_summary).
# ---------------------------------------------------------------------------
def test_population_summary_excludes_not_yet_finalized_liquidations(full_sample, full_models):
    pop = fl.population_lgd_summary(full_sample, full_models)
    row = pop.loc[pop["split"] == "train"].iloc[0]

    resolved = full_sample.loc[
        (full_sample["lgd_outcome"] != "unresolved") & (full_sample["split"] == "train")
    ].dropna(subset=["ltv10", "fico_s", "loan_age_at_default", "era", "property_state"])
    liq_no_loss = (resolved["lgd_outcome"] == "liquidation") & ~resolved["has_loss_data"]
    assert int(row["n_liq_excluded_no_loss_data"]) == int(liq_no_loss.sum())
    if liq_no_loss.sum() == 0:
        pytest.skip("this vintage has no 'loss not yet finalized' liquidations to distinguish on")

    # Reconstruct the WRONG zero-filled statistic and confirm the reported
    # mean_realized_lgd is NOT it (they'd coincide only if excluding vs.
    # zero-filling happened to net to the same mean, astronomically unlikely
    # whenever excluded rows exist and severities are nonzero).
    wrong_zero_filled = np.where(
        resolved["lgd_outcome"] == "cure", 0.0, resolved["severity"].fillna(0.0),
    ).mean()
    assert row["mean_realized_lgd"] != pytest.approx(wrong_zero_filled)

    # Correct value: cure -> 0, liquidation-with-loss-data -> severity,
    # liquidation-without-loss-data -> EXCLUDED (not averaged in at all).
    usable = resolved.loc[~liq_no_loss]
    correct = np.where(usable["lgd_outcome"] == "cure", 0.0, usable["severity"]).mean()
    assert row["mean_realized_lgd"] == pytest.approx(correct)
