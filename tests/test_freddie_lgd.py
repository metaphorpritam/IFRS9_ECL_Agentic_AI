# ---------------------------------------------------------------------------
# 1. Sign convention -- hand-traced fixture loans (raw zip, independent of
#    the module under test)
# ---------------------------------------------------------------------------
# F05Q10000744 (2005 vintage), terminal row 2011-10, zero_balance_code=="09"
# (REO disposition). Hand-traced via freddie.ingest.read_svcg_vintage(2005)
# and cross-checked against a direct raw-zip read (orchestrator transcript).
TRACE_LOAN_A_VINTAGE = 2005
TRACE_LOAN_A_ID = "F05Q10000744"
TRACE_LOAN_A = {
    "net_sale_proceeds": 3036.47,
    "mi_recoveries": 7521.0698,
    "non_mi_recoveries": 704.09998,
    "total_expenses": -6682.2798,          # already NEGATIVE on the raw tape
    "zero_balance_removal_upb": 22791.15,
    "delinquent_accrued_interest": 1783.88,
    "actual_loss_calculation": -19995.669921875,
}


def test_sign_convention_fixture_loan():
    """`actual_loss_calculation` reconciles (sub-dollar rounding) to
    net_sale_proceeds + mi_recoveries + non_mi_recoveries + total_expenses
    - zero_balance_removal_upb - delinquent_accrued_interest (lgd.py's
    module docstring). This is the empirical basis for realized_loss = -
    actual_loss_calculation -- checked against the raw tape, not assumed."""
    row = TRACE_LOAN_A
    computed = (
        row["net_sale_proceeds"] + row["mi_recoveries"] + row["non_mi_recoveries"]
        + row["total_expenses"] - row["zero_balance_removal_upb"] - row["delinquent_accrued_interest"]
    )
    assert computed == pytest.approx(row["actual_loss_calculation"], abs=1.0)
    # A shortfall (removal UPB + accrued interest not fully recovered by
    # proceeds/recoveries net of costs) makes actual_loss_calculation
    # NEGATIVE; realized_loss = -actual_loss_calculation must therefore be
    # POSITIVE (an economic loss, the common-sense direction).
    realized_loss = -row["actual_loss_calculation"]
    assert realized_loss > 0


def test_sign_convention_fixture_loan_traced_live():
    """Same fixture loan, re-traced live from the raw SFLLD zip (not the
    hardcoded numbers above) -- catches drift if ingest.py's parsing ever
    changes the reported values."""
    svcg = ingest.read_svcg_vintage(TRACE_LOAN_A_VINTAGE)
    sub = svcg.loc[svcg["loan_sequence_number"] == TRACE_LOAN_A_ID]
    term = sub.loc[sub["zero_balance_code"].notna()]
    assert not term.empty, f"{TRACE_LOAN_A_ID} has no terminal zero-balance row in {TRACE_LOAN_A_VINTAGE}"
    r = term.iloc[-1]
    assert str(r["zero_balance_code"]) == "09"
    computed = (
        float(r["net_sale_proceeds"]) + float(r["mi_recoveries"]) + float(r["non_mi_recoveries"])
        + float(r["total_expenses"]) - float(r["zero_balance_removal_upb"])
        - float(r["delinquent_accrued_interest"])
    )
    assert computed == pytest.approx(float(r["actual_loss_calculation"]), abs=1.0)
    assert float(r["actual_loss_calculation"]) == pytest.approx(
        TRACE_LOAN_A["actual_loss_calculation"], abs=1.0)


def test_sign_convention_holds_across_sample(sample):
    """Population-level lock (not just the one hand-traced loan): every
    liquidation row's realized_loss is the negation of the raw
    actual_loss_calculation column, and total_expenses (the sub-component
    Freddie already reports negative) never flips positive on a row with a
    populated loss field -- the sign discipline documented in lgd.py's
    module docstring holds across the whole small-vintage sample, not just
    the single fixture loan."""
    liq = sample.loc[sample["has_loss_data"]]
    assert len(liq) > 0
    pd.testing.assert_series_equal(
        liq["realized_loss"], -liq["actual_loss_calculation"],
        check_names=False,
    )


