def test_resolved_only_matches_dcr_convention(sample):
    """Same population fit_lgd_models trains on: cure + liquidation, minus
    unresolved -- mirrors DCR's "unresolved lgd_time is not a realised
    outcome" rule (engine/lgd.py, cited in lgd.py's module docstring)."""
    resolved = sample.loc[sample["lgd_outcome"] != "unresolved"]
