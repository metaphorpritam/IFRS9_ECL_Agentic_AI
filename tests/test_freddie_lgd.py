# 5. Economic sign assertions
#
# The cure-stage sign check (test_cure_falls_in_ltv) holds up fine on the
# single small vintage. The SEVERITY-stage LTV coefficient does not: fit on
# one origination cohort's ~4,200 liquidations, `ltv10`'s point estimate can
# legitimately flip sign (cohort-specific LTV/severity covariation, thin
# liq_year_bucket coverage within one vintage) -- fit_lgd_models's own
# economic-sign guard correctly RAISES on that fit rather than shipping a
# wrong-sign model (verified separately, see
# test_fit_lgd_models_thin_sample_can_legitimately_reject_wrong_sign below).
# The tests that need the sign to actually hold (and everything downstream
# of a successfully fitted LgdModels) therefore use `full_sample`/
# `full_models` -- the cached FULL 44,593-loan production sample, which is
# what fit_lgd.py actually ships and what the real ltv10 coefficients in
# outputs/freddie/lgd/lgd_report.md come from (cure -0.2475, severity
# +0.0307, both correctly signed).
# ---------------------------------------------------------------------------
def test_cure_falls_in_ltv(cure_model):
    assert cure_model.params["ltv10"] < 0


def test_fit_lgd_models_thin_sample_can_legitimately_reject_wrong_sign(sample):
    """Documents (rather than hides) the single-vintage severity sign flip:
    fit_lgd_models must raise AssertionError, not silently ship a model
    whose severity falls in LTV."""
    with pytest.raises(AssertionError, match="severity must RISE in updated LTV"):
        lgd.fit_lgd_models(sample, split=None)


def test_cure_falls_in_ltv_full_sample(full_models):
    assert full_models.cure_result.params["ltv10"] < 0


def test_severity_rises_in_ltv_full_sample(full_models):
    assert full_models.severity_result.params["ltv10"] > 0


def test_fit_lgd_models_end_to_end_sign_guard(full_models):
    """fit_lgd_models raises AssertionError if either economic sign is
    violated (lgd.py); on the full production sample (split="train",
    matching fit_lgd.py's own main()) it must fit cleanly and produce a
    well-formed LgdModels object."""
    models = full_models
    assert models.n_resolved > 0
    assert models.n_cure + models.n_liquidation == models.n_resolved
    assert 0.0 <= models.floor_mass <= 1.0
    assert models.excess_loading >= 0.0
    assert models.lgd_upper_bound == pytest.approx(models.sev_cap + models.excess_loading)


# ---------------------------------------------------------------------------
# 6. predict_components / predict_lgd contract
#
# predict_components must be scored on LIQUIDATION-outcome rows only (see
# its docstring): a cure row's disposition_type is a real, non-NaN value
# (prepaid_or_matured / rpl_securitization) but is a category the severity
# GLM never trained on, so it is EXCLUDED here explicitly, matching how
# freddie/fit_lgd.py's population_lgd_summary actually calls this function
# in production (never on the full resolved population).
# ---------------------------------------------------------------------------
def test_predict_components_bounded(full_sample, full_models):
    models = full_models
    scoring_cols = [
        "ltv10", "fico_s", "loan_age_at_default", "era", "property_state",
        "liq_year_bucket", "is_judicial", "disposition_type",
    ]
    df = full_sample[
        (full_sample["split"] == "train") & (full_sample["lgd_outcome"] == "liquidation")
    ].dropna(subset=scoring_cols)
    assert not df.empty
    out = lgd.predict_components(models, df)
    assert (out["lgd"] >= -1e-9).all()
    assert (out["lgd"] <= models.lgd_upper_bound + 1e-9).all()
    assert (out["p_cure"] >= 0.0).all() and (out["p_cure"] <= 1.0).all()
    lgd_np = lgd.predict_lgd(models, df)
    np.testing.assert_allclose(lgd_np, out["lgd"].to_numpy())


def test_predict_components_rejects_nan_covariates(full_sample, full_models):
    models = full_models
    scoring_cols = [
        "ltv10", "fico_s", "loan_age_at_default", "era", "property_state",
        "liq_year_bucket", "is_judicial", "disposition_type",
    ]
    df = full_sample[
        (full_sample["split"] == "train") & (full_sample["lgd_outcome"] == "liquidation")
    ].dropna(subset=scoring_cols).head(3).copy()
    assert not df.empty
    df.iloc[0, df.columns.get_loc("ltv10")] = np.nan
    with pytest.raises(ValueError):
        lgd.predict_components(models, df)


