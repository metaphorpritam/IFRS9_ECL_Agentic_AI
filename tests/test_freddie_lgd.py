# 4. Severity bounds after documented treatment
# ---------------------------------------------------------------------------
def test_severity_capped_in_bounds(sample):
    """sev_capped (severity.clip(0, SEV_CAP), what actually feeds the
    fractional-logit link) must lie in [0, SEV_CAP] -- never NaN/inf for
    rows with usable loss data."""
    liq = sample.loc[(sample["lgd_outcome"] == "liquidation") & sample["has_loss_data"]]
    if liq.empty:
        pytest.skip("no liquidation rows with loss data in this vintage")
    capped = liq["severity"].clip(lower=0.0, upper=lgd.SEV_CAP)
    assert np.isfinite(capped.to_numpy()).all()
    assert (capped >= 0.0).all()
    assert (capped <= lgd.SEV_CAP).all()


def test_raw_severity_can_exceed_bounds_but_is_finite(sample):
    """Unlike sev_capped, raw `severity` is DELIBERATELY not clipped (module
    docstring: the >1 / <0 tail is real, reported, never silently
    discarded) -- but it must still be finite, not NaN/inf, for every row
    with a populated loss field."""
    liq = sample.loc[(sample["lgd_outcome"] == "liquidation") & sample["has_loss_data"]]
    if liq.empty:
        pytest.skip("no liquidation rows with loss data in this vintage")
    assert np.isfinite(liq["severity"].to_numpy()).all()


def test_severity_is_nan_for_non_liquidation_or_no_loss_data(sample):
    """Rows without usable loss data must NOT carry a fabricated severity."""
    no_loss = sample.loc[~sample["has_loss_data"]]
    assert no_loss["actual_loss_calculation"].isna().all()


